#!/usr/bin/env node
/* Regenerates src/lib/body-paths.js from a checkout of MuscleMap by Melih Colpan (MIT, see NOTICE.md):
 *
 *   node scripts/build-body-paths.mjs <path to the MuscleMap checkout> [--check]
 *
 * MuscleMap ships its outlines as Swift source (Sources/MuscleMap/Data/{Male,Female}{Front,Back}Paths.swift),
 * one BodyPartPathData per part, each with `common`, `left` and `right` path lists. This reads those
 * four files as text (it never runs them) and writes a module of the shape
 *
 *   { male: { front: { vb, p: { chest: [d, ...], ... }, s: { 'upper-chest': [d, ...], ... } }, back: ... }, female: ... }
 *
 * `p` holds the whole muscles and the silhouette parts, as before. `s` holds the sub-regions MuscleMap
 * cuts from them (front-deltoid, upper-abs, inner-quad, rhomboids, ...), which the muscle explorer can
 * draw and tell apart (lib/muscle-regions.js). The two are kept apart so a screen that shades whole
 * muscles never paints a sub-region over them. */
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../src/lib/body-paths.js')
const VIEWBOX = {
  maleFront: '0 95 727 1280', maleBack: '718 95 727 1280', femaleFront: '0 0 650 1450', femaleBack: '823 0 650 1450',
}
// MuscleMap's own sub-regions: everything else is a whole muscle or a silhouette part.
const SUB = new Set(['upperChest', 'lowerChest', 'innerQuad', 'outerQuad', 'hipFlexors', 'upperAbs', 'lowerAbs', 'frontDeltoid', 'rearDeltoid',
  'upperTrapezius', 'lowerTrapezius', 'rotatorCuff', 'rhomboids'])
const kebab = s => s.replace(/[A-Z]/g, c => '-' + c.toLowerCase())
// hipFlexors was always a part of its own in this app's muscle list, so it stays in `p`.
const isSub = slug => SUB.has(slug) && slug !== 'hipFlexors'

function parse(src) {
  const parts = {}
  // Each BodyPartPathData( slug: .name, common: [...], left: [...], right: [...] )
  const re = /BodyPartPathData\(\s*slug:\s*\.(\w+)([\s\S]*?)\n\s{8}\)/g
  for (const m of src.matchAll(re)) {
    const [, slug, body] = m
    const list = key => {
      const a = new RegExp(`${key}:\\s*\\[([\\s\\S]*?)\\]`).exec(body)
      return a ? [...a[1].matchAll(/"([^"]+)"/g)].map(x => x[1]) : []
    }
    parts[slug] = [...list('common'), ...list('left'), ...list('right')]
  }
  return parts
}

export function build(root) {
  const out = {}
  for (const [gender, G] of [['male', 'Male'], ['female', 'Female']]) {
    out[gender] = {}
    for (const [side, S] of [['front', 'Front'], ['back', 'Back']]) {
      const parts = parse(readFileSync(join(root, `Sources/MuscleMap/Data/${G}${S}Paths.swift`), 'utf8'))
      const p = {}, s = {}
      for (const [slug, d] of Object.entries(parts)) (isSub(slug) ? s : p)[kebab(slug)] = d
      out[gender][side] = { vb: VIEWBOX[gender + S], p, ...(Object.keys(s).length ? { s } : {}) }
    }
  }
  return out
}

const HEAD = `// Body geometry — the SVG outlines every muscle map in the app is drawn from.
//
// Converted from MuscleMap by Melih Colpan (MIT), whose path data ships as Swift
// source rather than .svg files; see NOTICE.md. Four views (male/female ×
// front/back), each a viewBox plus one path list per body part (\`p\`) and, where
// MuscleMap cuts them, one per sub-region (\`s\`: front-deltoid, upper-abs, inner-quad,
// rhomboids …). Parts that are not muscles — head, hair, neck, hands, feet, knees,
// ankles — are drawn as the silhouette and never take a heat colour; see INERT in
// lib/muscles.js.
//
// The heat maps shade whole muscles, because the exercise dataset resolves to whole
// muscles; only the muscle explorer draws \`s\` (lib/muscle-regions.js says how an
// exercise is matched to a region).
//
// ~140 KB, so this module is imported dynamically and only lands in the bundle
// once a muscle map is actually shown. Generated by scripts/build-body-paths.mjs — do not hand-edit.

`

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = process.argv[2]
  if (!root) { console.error('usage: node scripts/build-body-paths.mjs <MuscleMap checkout> [--check]'); process.exit(2) }
  const text = HEAD + 'export default ' + JSON.stringify(build(root)) + '\n'
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== text) { console.error('src/lib/body-paths.js is out of date'); process.exit(1) }
    console.log('body paths up to date')
  } else { writeFileSync(OUT, text); console.log('wrote src/lib/body-paths.js,', Buffer.byteLength(text), 'bytes') }
}
